#!/usr/bin/env python3
"""
Generate blend_table.h: RDP configurations that reproduce GBA alpha blending
    out = min(31, (a*EVA + b*EVB) >> 4)        (per 5-bit channel)
inside the renderer's 32-bit "quarter scale" intermediate surface.

Model of the RDP arithmetic (angrylion / paraLLEl-RDP):
  texel (TLUT RGBA16)  T8(t) = (t<<3) | (t>>2)
  combiner             clamp9(((A-B)*C + (D<<8) + 0x80) >> 8)
  blender (force)      ((X*a1 + Y*mulb) >> 5), a1 = alpha>>3, mulb = 32-a1 (INV) or 32 (ONE)
Intermediate representation of an unblended colour c is v = 4c (combiner TEX*124);
the final pass maps v -> min(31, v>>2) exactly (2-cycle combiner, see gba_render.c).

For every (EVA, EVB>0) the script picks: blender variant, a1, combiner variant/constant
and a per-channel remap tau[32] that the CPU applies to the first-target TLUT.
Exact configurations are preferred; otherwise the one with the fewest wrong (a,b)
pairs is used (the error count is recorded in the table).

Usage: python3 gen_blend_table.py > blend_table.h
"""
import sys
import numpy as np

def T8(t): return (t << 3) | (t >> 2)
def clamp9(v):
    v &= 0x1ff
    return v if v < 256 else (255 if v < 384 else 0)
def comb(a, b, c, d): return clamp9((((a - b) * c + (d << 8) + 0x80) & 0x1ffff) >> 8)

V = np.array([4 * c for c in range(32)])            # intermediate of b
def fin(o): return np.minimum(31, o >> 2)

# combiner candidates: (kind, C) -> P(t) for t in 0..31
cands = {}
for C in range(256):
    cands[(0, C)] = [comb(T8(t), 0, C, 0) for t in range(32)]          # TEX*C
    cands[(1, C)] = [comb(T8(t), 0, C, T8(t)) for t in range(32)]      # TEX*C + TEX
# dedupe by set
sets = {}
for k, ps in cands.items():
    key = tuple(sorted(set(ps)))
    if key not in sets: sets[key] = k
set_keys = list(sets.keys())
S = np.zeros((len(set_keys), 256), bool)
for i, key in enumerate(set_keys): S[i, list(key)] = True

A = np.arange(32)[:, None, None]       # a
P = np.arange(256)[None, :, None]      # P
B = np.arange(32)[None, None, :]       # b
VARIANTS = [(0, 'P*a1+M*INV'), (1, 'P*a1+M*ONE'), (2, 'M*a1+P*INV'), (3, 'M*a1+P*ONE')]

def best(eva, evb):
    tgt = np.minimum(31, (A * eva + B * evb) >> 4)        # 32 x 1 x 32
    bestc = None
    for var, _ in VARIANTS:
        for a1 in range(32):
            mulb = 32 - a1 if var in (0, 2) else 32
            if var < 2: o = (P * a1 + V[B] * mulb) >> 5
            else:       o = (V[B] * a1 + P * mulb) >> 5
            ok = (o <= 255) & (fin(o) == tgt)
            err = 32 - ok.sum(axis=2)                       # 32 x 256 wrong b's per (a,P)
            # cost per set: sum_a min_{P in set} err[a,P]
            big = np.where(S[:, None, :], err[None, :, :], 99)   # Ns x 32 x 256
            m = big.min(axis=2)                                   # Ns x 32
            cost = m.sum(axis=1)
            i = int(cost.argmin())
            c = int(cost[i])
            if bestc is None or c < bestc[0]:
                Pch = big[i].argmin(axis=1)                       # chosen P per a
                bestc = (c, var, a1, i, Pch.copy())
                if c == 0: return bestc
    return bestc

out = []
for eva in range(17):
    for evb in range(1, 17):
        c, var, a1, si, Pch = best(eva, evb)
        kind, C = sets[set_keys[si]]
        ps = cands[(kind, C)]
        tau = [ps.index(int(Pch[a])) for a in range(32)]
        out.append((eva, evb, var, a1, kind, C, c, tau))
        print(f"eva={eva:2d} evb={evb:2d} var={VARIANTS[var][1]} a1={a1:2d} comb={kind}/{C:3d} wrong={c}", file=sys.stderr)

print("/* Generated by gen_blend_table.py - do not edit. */")
print("#ifndef BLEND_TABLE_H\n#define BLEND_TABLE_H\n#include <stdint.h>")
print("/* variant: 0 P*a1+M*(1-a), 1 P*a1+M, 2 M*a1+P*(1-a), 3 M*a1+P   (P = combiner, M = memory)")
print(" * comb: 0 TEX*C, 1 TEX*C+TEX;  wrong = model-predicted wrong (a,b) pairs of 1024 */")
print("typedef struct { uint8_t variant, a1, comb, C; uint16_t wrong; uint8_t tau[32]; } blend_cfg_t;")
print("static const blend_cfg_t blend_table[17][16] = {  /* [eva][evb-1] */")
for eva in range(17):
    print("  {")
    for (e, evb, var, a1, kind, C, c, tau) in out:
        if e != eva: continue
        print(f"    {{{var},{a1},{kind},{C},{c},{{{','.join(map(str, tau))}}}}},")
    print("  },")
print("};\n#endif")
